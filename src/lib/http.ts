/**
 * Read a request body as text with a hard byte cap, before any JSON.parse. Returns null when the body
 * is larger than `maxBytes` (the stream is cancelled as soon as the cap is crossed).
 */
export async function readTextCapped(request: Request, maxBytes: number): Promise<string | null> {
  const declared = Number(request.headers.get("content-length"));
  if (Number.isFinite(declared) && declared > maxBytes) return null;
  if (!request.body) return "";
  const reader = request.body.getReader();
  const chunks: Uint8Array[] = [];
  let total = 0;
  for (;;) {
    const { done, value } = await reader.read();
    if (done) break;
    total += value.byteLength;
    if (total > maxBytes) {
      await reader.cancel().catch(() => undefined);
      return null;
    }
    chunks.push(value);
  }
  const buf = new Uint8Array(total);
  let off = 0;
  for (const c of chunks) {
    buf.set(c, off);
    off += c.byteLength;
  }
  return new TextDecoder().decode(buf);
}

export function isJsonContentType(request: Request): boolean {
  return (request.headers.get("content-type") ?? "").toLowerCase().split(";")[0].trim() === "application/json";
}
